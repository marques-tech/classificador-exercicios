# #########################################################
# ETAPA 1 - IMPORTAÇÃO DAS BIBLIOTECAS
# #########################################################

# Nesta etapa, importamos as bibliotecas que serão utilizadas
# durante a atividade.
#
# requests:
# Permite realizar requisições HTTP a servidores e APIs.
#
# pandas:
# Permite organizar, manipular e analisar os dados em tabelas.
#
# matplotlib:
# Permite construir gráficos para visualizar os dados coletados.

import requests
import pandas as pd
import matplotlib.pyplot as plt

# Configura algumas opções de visualização do Pandas.
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 120)

# #########################################################
# ETAPA 2 - DEFINIÇÃO DO ENDPOINT E DOS PARÂMETROS
# PRIMEIRA CONSULTA: POUSO ALEGRE
# #########################################################

# O endpoint é o endereço da API que disponibiliza
# os dados meteorológicos.
#
# Utilizaremos o serviço de previsão do Open-Meteo.

url = "https://api.open-meteo.com/v1/forecast"

# Agora definimos os parâmetros que serão enviados à API.
#
# latitude e longitude:
# Identificam a localização geográfica da consulta.
#
# hourly:
# Indica quais variáveis meteorológicas desejamos obter
# em frequência horária.
#
# forecast_days:
# Define o horizonte da previsão. Neste exemplo,
# solicitamos os dados para um dia.
#
# timezone:
# Define o fuso horário utilizado na apresentação dos horários.

parametros = {
    "latitude": -22.23,
    "longitude": -45.94,
    "hourly": (
        "temperature_2m,"
        "relative_humidity_2m,"
        "precipitation,"
        "wind_speed_10m"
    ),
    "forecast_days": 1,
    "timezone": "America/Sao_Paulo"
}

# #########################################################
# ETAPA 3 - REALIZAÇÃO DA REQUISIÇÃO HTTP
# #########################################################

# Utilizamos requests.get() para enviar uma requisição
# HTTP utilizando o método GET.
#
# O primeiro argumento é o endereço da API.
# O segundo argumento contém os parâmetros da consulta.
# O parâmetro timeout estabelece um limite de espera
# pela resposta do servidor.
#
# O resultado da comunicação é armazenado no objeto resposta.

resposta = requests.get(
    url,
    params=parametros,
    timeout=30
)

# Exibimos a URL completa construída pelo Requests.
# Observe que os parâmetros foram incorporados ao endereço.

print("URL da requisição:")
print(resposta.url)

# #########################################################
# ETAPA 4 - VERIFICAÇÃO DO CÓDIGO DE RESPOSTA HTTP
# #########################################################

# Antes de interpretar os dados, precisamos verificar
# o resultado da comunicação com o servidor.
#
# O atributo status_code informa o código HTTP recebido.
#
# O código 200 indica que a requisição foi processada
# com sucesso.
#
# O método raise_for_status() interrompe a execução
# caso a resposta indique um erro HTTP.

print("Código de resposta HTTP:", resposta.status_code)

resposta.raise_for_status()

print("Requisição realizada com sucesso!")

# #########################################################
# ETAPA 5 - INTERPRETAÇÃO DA RESPOSTA JSON
# #########################################################

# A API retorna os dados no formato JSON.
#
# O método json() interpreta o conteúdo recebido
# e o converte para estruturas de dados do Python.
#
# Neste caso, a resposta será representada principalmente
# por um dicionário, que contém outros dicionários e listas.

dados = resposta.json()

# Exibimos a estrutura completa para observar
# como a API organizou as informações.

print("Resposta JSON:")
print(dados)

# #########################################################
# ETAPA 6 - EXPLORAÇÃO DA ESTRUTURA JSON
# #########################################################

# Antes de extrair os valores, precisamos compreender
# como as informações estão organizadas.
#
# O método keys() permite visualizar as chaves
# existentes em um dicionário.
#
# Esperamos encontrar informações gerais da consulta
# e um objeto chamado hourly, que contém os dados horários.

print("Chaves principais da resposta:")
print(dados.keys())

print("\nChaves do objeto hourly:")
print(dados["hourly"].keys())

# Exibimos especificamente o objeto hourly.

print("\nDados meteorológicos horários:")
print(dados["hourly"])

# #########################################################
# ETAPA 7 - EXTRAÇÃO DAS VARIÁVEIS METEOROLÓGICAS
# #########################################################

# O objeto hourly contém listas associadas às variáveis
# meteorológicas solicitadas.
#
# Cada posição dessas listas corresponde a um horário.
#
# Por exemplo:
# O primeiro elemento da lista de temperaturas corresponde
# ao primeiro horário da lista time.
#
# Essa correspondência será importante para construir
# posteriormente nossa tabela.

horarios = dados["hourly"]["time"]

temperaturas = dados["hourly"]["temperature_2m"]

umidades = dados["hourly"]["relative_humidity_2m"]

precipitacoes = dados["hourly"]["precipitation"]

ventos = dados["hourly"]["wind_speed_10m"]

# Verificamos a quantidade de observações retornadas.

print("Quantidade de horários:", len(horarios))

# Exibimos algumas observações para compreender
# a correspondência entre horários e valores.

print("\nPrimeiros horários:")
print(horarios[:3])

print("\nTemperaturas correspondentes:")
print(temperaturas[:3])

print("\nUmidades correspondentes:")
print(umidades[:3])

# #########################################################
# ETAPA 8 - CONSTRUÇÃO DO DATAFRAME
# CIDADE: POUSO ALEGRE
# #########################################################

# Agora vamos organizar as informações extraídas
# em uma estrutura tabular utilizando o Pandas.
#
# Um DataFrame é uma tabela formada por linhas e colunas.
#
# Cada linha representará um horário da previsão.
# Cada coluna representará uma variável meteorológica.

df_pouso_alegre = pd.DataFrame({

    "data_hora": horarios,

    "temperatura_C": temperaturas,

    "umidade_relativa_%": umidades,

    "precipitacao_mm": precipitacoes,

    "vento_km_h": ventos

})

# Convertemos a coluna data_hora para o tipo datetime.
# Isso facilita operações temporais e a construção de gráficos.

df_pouso_alegre["data_hora"] = pd.to_datetime(
    df_pouso_alegre["data_hora"]
)

# Exibimos as primeiras linhas da tabela.

print("Dados meteorológicos de Pouso Alegre:")

display(df_pouso_alegre.head())

# Verificamos a quantidade de linhas e colunas.

print("\nDimensões do DataFrame:")

print(df_pouso_alegre.shape)

# #########################################################
# ETAPA 09 - EXPORTAÇÃO DA BASE PARA CSV
# #########################################################

# Finalmente, vamos salvar a base de dados construída
# em um arquivo CSV.
#
# CSV é um formato textual utilizado para armazenar
# dados organizados em linhas e colunas.
#
# O parâmetro index=False evita salvar o índice do DataFrame
# como uma coluna adicional.
#
# A codificação utf-8-sig ajuda na compatibilidade
# com programas que abrem arquivos CSV, como o Excel.

nome_arquivo = "pa_dados_meteorologicos.csv"

df_pouso_alegre.to_csv(
    nome_arquivo,
    index=False,
    encoding="utf-8-sig"
)

print("Arquivo exportado com sucesso:", nome_arquivo)

# #########################################################
# ETAPA 10 - DOWNLOAD DO ARQUIVO NO GOOGLE COLAB
# #########################################################

# Esta etapa permite baixar o arquivo CSV gerado
# diretamente para o computador.
#
# A biblioteca files é disponibilizada pelo Google Colab.

from google.colab import files

files.download(nome_arquivo)

# #########################################################
# ETAPA 11 - DEFINIÇÃO DAS CIDADES PARA A COLETA
# #########################################################

# Depois de compreender o procedimento para uma cidade,
# vamos ampliar nossa coleta.
#
# Utilizaremos três cidades brasileiras:
#
# Pouso Alegre, Itajubá e Belo Horizonte.
#
# Para cada cidade, precisamos informar sua latitude
# e longitude aproximadas.
#
# Organizamos essas informações em um dicionário.
# O nome da cidade será a chave e suas coordenadas
# serão os respectivos valores.

cidades = {

    "Pouso Alegre": {
        "latitude": -22.23,
        "longitude": -45.94
    },

    "Itajubá": {
        "latitude": -22.43,
        "longitude": -45.45
    },

    "Belo Horizonte": {
        "latitude": -19.92,
        "longitude": -43.94
    }

}

# #########################################################
# ETAPA 12 - CRIAÇÃO DE UMA FUNÇÃO DE COLETA
# #########################################################

# Observe que, para cada cidade, precisamos realizar
# praticamente as mesmas operações:
#
# 1. Construir os parâmetros da requisição.
# 2. Enviar a requisição à API.
# 3. Verificar a resposta HTTP.
# 4. Interpretar o JSON.
# 5. Extrair as variáveis meteorológicas.
# 6. Construir um DataFrame.
#
# Para evitar repetir todo esse código, vamos criar
# uma função chamada coletar_dados_cidade().
#
# A função recebe o nome da cidade e suas coordenadas.
# Como resultado, retorna um DataFrame com os dados coletados.

def coletar_dados_cidade(nome_cidade, latitude, longitude):

    # Definição dos parâmetros da consulta.
    parametros = {

        "latitude": latitude,

        "longitude": longitude,

        "hourly": (
            "temperature_2m,"
            "relative_humidity_2m,"
            "precipitation,"
            "wind_speed_10m"
        ),

        "forecast_days": 1,

        "timezone": "America/Sao_Paulo"

    }

    # Envio da requisição GET à API.
    resposta = requests.get(
        url,
        params=parametros,
        timeout=30
    )

    # Verificação da resposta HTTP.
    # Se houver erro, a execução da função será interrompida.
    resposta.raise_for_status()

    # Conversão da resposta JSON para estruturas Python.
    dados = resposta.json()

    # Acessamos o objeto que contém os dados horários.
    dados_horarios = dados["hourly"]

    # Construção do DataFrame com as variáveis solicitadas.
    df_cidade = pd.DataFrame({

        "data_hora": dados_horarios["time"],

        "temperatura_C": dados_horarios["temperature_2m"],

        "umidade_relativa_%": dados_horarios["relative_humidity_2m"],

        "precipitacao_mm": dados_horarios["precipitation"],

        "vento_km_h": dados_horarios["wind_speed_10m"]

    })

    # Conversão da coluna temporal para datetime.
    df_cidade["data_hora"] = pd.to_datetime(
        df_cidade["data_hora"]
    )

    # Acrescentamos uma coluna identificando a cidade.
    # Isso permitirá reunir os dados em uma única tabela
    # sem perder a informação de sua origem.
    df_cidade["cidade"] = nome_cidade

    # Retornamos o DataFrame construído.
    return df_cidade

# #########################################################
# ETAPA 13 - COLETA DOS DADOS DAS TRÊS CIDADES
# #########################################################

# Criamos uma lista vazia para armazenar os DataFrames
# produzidos pela função de coleta.
#
# O comando for percorre o dicionário cidades.
#
# Em cada repetição:
# 1. Obtemos o nome da cidade.
# 2. Obtemos suas coordenadas.
# 3. Chamamos a função de coleta.
# 4. Armazenamos o DataFrame retornado na lista.

lista_dataframes = []

for nome, coordenadas in cidades.items():

    df_cidade = coletar_dados_cidade(
        nome,
        coordenadas["latitude"],
        coordenadas["longitude"]
    )

    lista_dataframes.append(df_cidade)

    print(
        f"{nome}: {len(df_cidade)} registros coletados."
    )

# #########################################################
# ETAPA 14 - CONSTRUÇÃO DA BASE DE DADOS COMPLETA
# #########################################################

# Agora temos três DataFrames, um para cada cidade.
#
# Utilizaremos pd.concat() para reunir essas tabelas
# em um único DataFrame.
#
# O parâmetro ignore_index=True cria uma nova sequência
# de índices para a tabela resultante.

df = pd.concat(
    lista_dataframes,
    ignore_index=True
)

# Reorganizamos as colunas para facilitar a leitura.

df = df[
    [
        "cidade",
        "data_hora",
        "temperatura_C",
        "umidade_relativa_%",
        "precipitacao_mm",
        "vento_km_h"
    ]
]

# Exibimos as primeiras linhas da base completa.

print("Base de dados meteorológicos:")

display(df.head(10))

# Verificamos as dimensões da base.

print("\nDimensões da base:")

print(df.shape)

# #########################################################
# ETAPA 15 - VERIFICAÇÃO E INSPEÇÃO DA BASE
# #########################################################

# Antes de iniciar a análise, precisamos conhecer
# algumas características da base construída.
#
# Vamos verificar:
# 1. Quantidade de registros por cidade.
# 2. Tipos de dados de cada coluna.
# 3. Existência de valores ausentes.

print("Quantidade de registros por cidade:")

print(df["cidade"].value_counts())

print("\nTipos de dados:")

print(df.dtypes)

print("\nQuantidade de valores ausentes por coluna:")

print(df.isna().sum())

# #########################################################
# ETAPA 16 - ESTATÍSTICAS DESCRITIVAS
# #########################################################

# Utilizaremos o método describe() para calcular
# medidas estatísticas descritivas das variáveis numéricas.
#
# Entre as medidas apresentadas estão:
# count: quantidade de observações;
# mean: média;
# std: desvio padrão;
# min: valor mínimo;
# 25%, 50% e 75%: quartis;
# max: valor máximo.

print("Estatísticas descritivas:")

display(
    df[
        [
            "temperatura_C",
            "umidade_relativa_%",
            "precipitacao_mm",
            "vento_km_h"
        ]
    ].describe()
)

# #########################################################
# ETAPA 17 - COMPARAÇÃO DAS CIDADES
# MÉDIAS DAS VARIÁVEIS METEOROLÓGICAS
# #########################################################

# Queremos comparar o comportamento das variáveis
# meteorológicas entre as três cidades.
#
# O método groupby() agrupa os registros de acordo
# com o nome da cidade.
#
# Em seguida, calculamos a média de cada variável
# para cada grupo.
#
# O resultado será uma tabela comparativa.

resumo_cidades = (

    df.groupby("cidade")[

        [
            "temperatura_C",
            "umidade_relativa_%",
            "precipitacao_mm",
            "vento_km_h"
        ]

    ]

    .mean()

    .round(2)

)

print("Médias das variáveis meteorológicas por cidade:")

display(resumo_cidades)

# #########################################################
# ETAPA 18 - VISUALIZAÇÃO DA TEMPERATURA AO LONGO DO TEMPO
# #########################################################

# Vamos construir um gráfico de linhas para comparar
# a evolução horária da temperatura nas três cidades.
#
# Cada linha representa uma cidade.
# O eixo horizontal representa o horário.
# O eixo vertical representa a temperatura em graus Celsius.

plt.figure(figsize=(11, 5))

for cidade, grupo in df.groupby("cidade"):

    plt.plot(
        grupo["data_hora"],
        grupo["temperatura_C"],
        marker="o",
        label=cidade
    )

plt.title("Previsão horária de temperatura")

plt.xlabel("Data e hora")

plt.ylabel("Temperatura (°C)")

plt.xticks(rotation=45)

plt.legend()

plt.grid(True)

plt.tight_layout()

plt.show()

# #########################################################
# ETAPA 19 - COMPARAÇÃO DA TEMPERATURA MÉDIA
# #########################################################

# Agora construiremos um gráfico de barras.
#
# Cada barra representa a temperatura média prevista
# para uma das cidades durante o período consultado.
#
# Esse gráfico facilita a comparação entre os valores médios.

temperatura_media = (
    df.groupby("cidade")["temperatura_C"].mean()
)

plt.figure(figsize=(8, 5))

temperatura_media.plot(kind="bar")

plt.title("Temperatura média prevista por cidade")

plt.xlabel("Cidade")

plt.ylabel("Temperatura média (°C)")

plt.xticks(rotation=0)

plt.grid(axis="y")

plt.tight_layout()

plt.show()

# #########################################################
# ETAPA 20 - COMPARAÇÃO DA PRECIPITAÇÃO ACUMULADA
# #########################################################

# A variável precipitation representa a precipitação
# prevista em cada intervalo horário, em milímetros.
#
# Vamos somar os valores horários para obter
# a precipitação acumulada prevista durante o período
# consultado para cada cidade.
#
# Em seguida, construiremos um gráfico de barras.

precipitacao_total = (
    df.groupby("cidade")["precipitacao_mm"].sum()
)

plt.figure(figsize=(8, 5))

precipitacao_total.plot(kind="bar")

plt.title("Precipitação acumulada prevista")

plt.xlabel("Cidade")

plt.ylabel("Precipitação acumulada (mm)")

plt.xticks(rotation=0)

plt.grid(axis="y")

plt.tight_layout()

plt.show()

# #########################################################
# ETAPA 21 - EXPORTAÇÃO DA BASE PARA CSV
# #########################################################

# Finalmente, vamos salvar a base de dados construída
# em um arquivo CSV.
#
# CSV é um formato textual utilizado para armazenar
# dados organizados em linhas e colunas.
#
# O parâmetro index=False evita salvar o índice do DataFrame
# como uma coluna adicional.
#
# A codificação utf-8-sig ajuda na compatibilidade
# com programas que abrem arquivos CSV, como o Excel.

nome_arquivo = "dados_meteorologicos.csv"

df.to_csv(
    nome_arquivo,
    index=False,
    encoding="utf-8-sig"
)

print("Arquivo exportado com sucesso:", nome_arquivo)

